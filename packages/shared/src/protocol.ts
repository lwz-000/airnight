/** 把结构化消息转成可以走 WebSocket 的字符串 */
export function encodeMessage(message: ServerMessage | ClientMessage): string {
  return JSON.stringify(message);
}

/**
 * 解析收到的消息。
 * 故意做得「不信任输入」：格式不对就返回 null，而不是抛异常崩溃。
 * 因为网络对面可能是随便什么程序（甚至是恶意脚本）。
 */
export function decodeMessage<T extends ServerMessage | ClientMessage>(raw: string): T | null {
  try {
    const parsed = JSON.parse(raw) as unknown;
    if (parsed && typeof parsed === 'object' && typeof (parsed as { t?: unknown }).t === 'string') {
      return parsed as T;
    }
    return null;
  } catch {
    return null;
  }
}

/** 房间码：去掉容易看错的字符（0/O、1/I），方便口头念给朋友 */
export const CODE_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';

/** 房间码长度（改这里就等于改所有界面上的提示，别在别处写死 6） */
export const ROOM_CODE_LENGTH = 6;

/**
 * 生成 6 位房间码。
 *
 * 【0.0.3 末修的一个真 bug：房间码一点都不随机】
 * 老写法是 `CODE_ALPHABET[random() % ALPHABET.length]`，而调用方给的是一个
 * **从固定种子 1 开始的线性同余发生器**（`seed = (seed*1103515245+12345) % 2^31`）。
 * 两件事叠在一起，结果是：
 *   · `% 32` 取的是这个发生器的**最低 5 位**，而 LCG 低位周期极短（≤32）；
 *   · 种子写死成 1，所以**每次开服的前几个房间号一模一样**。
 * 实测（`RoomManager` 连开 3 次服）：每次都是 `GAAAAA`、`A2AAAA`、`AAAAAA`、`AAAA2A`…
 * —— 六个字符里五个是 A，朋友看了一眼就会以为是代码写死的。
 *
 * 【现在的约定】`random()` 必须是 **[0, 1) 均匀分布**（服务器用
 * `crypto.randomInt` 换算，见 room.ts；测试里可以塞一个确定性序列）。
 * 这样取值用的是全量随机位，而不是低位。
 */
export function generateRoomCode(random: () => number): string {
  let code = '';
  for (let i = 0; i < ROOM_CODE_LENGTH; i++) {
    // 夹一下，防止调用方给出 1.0 或负数时越界
    const r = Math.min(0.9999999, Math.max(0, random()));
    code += CODE_ALPHABET[Math.floor(r * CODE_ALPHABET.length)];
  }
  return code;
}

/**
 * 这个房间码"看起来太假"吗（全同一个字 / 连续好几个重复 / 只有两种字符）。
 *
 * 【为什么要它？】
 * 均匀随机也会偶尔掷出 `AAAAAA`（概率 1/32^5）和 `QQQQQQ` 这种。
 * 概率上没问题，但朋友看到会怀疑"这房间号是不是没随机"，
 * 而且口头念的时候容易听错（"AAAAAA" 和 "AAAAA A" 谁分得清）。
 * 所以服务器生成时避开它们 —— 代价是重掷几次，可以忽略。
 */
export function isDullRoomCode(code: string): boolean {
  // 连续 3 个及以上相同字符（AAAA.. / ..BBB..）
  if (/(.)\1{2,}/.test(code)) return true;
  // 去重之后太少（只有 1~2 种字符）：AAAAAA / ABABAB 这类
  if (new Set(code).size < 3) return true;
  return false;
}

/** 房间码是否合法（用户手输时要校验） */
export function isValidRoomCode(code: string): boolean {
  if (code.length !== 6) return false;
  for (const char of code) {
    if (!CODE_ALPHABET.includes(char)) return false;
  }
  return true;
}


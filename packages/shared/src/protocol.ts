/**
 * ★ 0.0.3：客户端**提交**的阵容（`submitTeam` 的载荷）。
 *
 * 【为什么不是直接发一整个 TeamSetup？】
 * 因为 `TeamSetup` 里的 `traitBonuses` / `activeTraits` / `unitMechanics`
 * 是**服务端自己算的** —— 见 `Room.buildTeamSetup` 的注释：
 * "谁吃到什么加成由服务器说了算，客户端改不了"。
 * 所以客户端只提交**原始输入**，服务器收到后重新解析成完整的 TeamSetup。
 *
 * 【为什么 0.0.3 要加两个字段？—— 这里曾经漏过】
 * 加了藏品之后，"原始输入"就不只是棋子站位了：
 *   · `items`（挂在每个 UnitPlacement 上）—— A 类藏品。
 *     曾经客户端只发 `{defId, star, cell}`，把 items 扔掉了，
 *     于是联机时**服务器算出来的结果根本没有藏品加成**，
 *     玩家在布阵界面看着"装备已生效"，打起来却一点效果都没有。
 *   · `sharedItems` + `playerContext` —— B 类藏品，以及它要看的玩家金币 / 血量。
 *     同理，不带就等于联机里 B 类藏品全废。
 * 教训和"拖拽落子"那次一样：**同一份数据只允许一处构造**。
 * 所以客户端现在直接发 `toTeamSetup(state)` 的产物（见 syncTeamToServer），
 * 而不是自己另拼一份 `{defId, star, cell}`。
 */
/**
 * ★ 0.1.1：备战席上的一枚棋子（随阵容一起上报给服务器）。
 *
 * 【为什么要把备战席也传上去？】
 * 以前客户端只发"场上的棋子"，服务器对备战席一无所知。于是两件事办不到：
 *   1. **观战**：点别人看他棋盘时，只能看到站着的，看不到他手里还攒着什么
 *      （而"他备战席里蹲着三张同名卡"恰恰是最有信息量的部分）。
 *   2. **淘汰回库**：玩家出局后要把手上的牌还给共享牌库 ——
 *      服务器连有哪些牌都不知道，只能漏掉，那些牌就永远回不来了。
 *
 * 【为什么带 `copies` 而不是让服务器自己按星级算？】
 * 因为"这枚棋子占牌库几张"有一层 `free` 语义（修改器白送的、拟态物质复制的
 * 一张都不占）。那套换算的唯一实现在 `shared/economy.ts` 的 `poolCopiesOf()`，
 * 客户端算好直接发过来，服务器不去猜。
 */
export interface BenchUnitView {
  defId: string;
  star: number;
  /** 这枚棋子占牌库几张（白送的写 0；换算见 economy.ts 的 poolCopiesOf） */
  copies: number;
}

/**
 * ★★ 0.3.4：某位玩家的**藏品栏视图**（观战用，只读）。
 *
 * 【为什么现在才需要】
 * 用户口径：「在多人模式观战时可以看到其他人的藏品栏位」。
 * 以前观战只能看到场上的棋子和备战席 —— 藏品栏还是**我自己**的，
 * 切到别人的棋盘上却看着自己的藏品，非常容易误判（"他哪来这么多共享藏品"）。
 *
 * 【数据从哪来】
 * 服务端本来就有：`SubmittedTeam.itemState.bag`（a / b / cert）是断线重连用的，
 * `SubmittedTeam.sharedItems` 是共享装备位那 4 格。这里只是把**同一份数据**
 * 换个只读视图转发出去，不需要客户端多报任何东西。
 *
 * ★ 四个数组长度固定（空格子是 `null`），界面直接按格子画。
 */
export interface PrepItemView {
  /** A 类存放区（10 格） */
  a: (string | null)[];
  /** B 类存放区（5 格） */
  b: (string | null)[];
  /** 共享装备位（4 格） */
  bEquip: (string | null)[];
  /** 升变之证专用栏（3 格） */
  cert: (string | null)[];
}

/**
 * ★ 0.1.1：布阵期间广播给房间的「某个玩家的阵容视图」。
 *
 * `units` = 场上的（看棋盘用），`bench` = 备战席的（观战时也看得到）。
 * ★ 0.3.4：多了 `items` —— 观战时**藏品栏也换成他的**（只读）。
 */
export interface PrepTeamView {
  units: UnitPlacement[];
  bench: BenchUnitView[];
  /** ★ 0.3.4：他的藏品栏（只读）。老客户端不读它也不会坏 */
  items?: PrepItemView;
}

/**
 * ★ 0.1.1：联机对局结算页里**一位玩家**的战绩。
 *
 * 【四项内容分别是给结算页的哪个模块用的】
 *   1. 玩家排名系统      -> `rank` / `name` / `avatarId` / `level` / `hp` / 胜负 / `eliminatedRound`
 *   2. 死亡时的干员阵容  -> `lineup`（服务器已**按费用从低到高排好**，见 Room.standings）
 *   3. 该玩家激活的羁绊  -> `traits`（只发**已生效**的，没凑齐的不发）
 *   4. 伤害最高的干员    -> `topUnit`（整局按 defId 累计）+ `totalDamage`
 *
 * 【为什么阵容里保留 cell？】
 * 结算页只按费用排序展示、不画棋盘，`cell` 其实用不上 ——
 * 但类型直接复用 `UnitPlacement` 省得再造一个形状，
 * 而且以后想加"看他的站位"就不用再改协议了。
 */
export interface PlayerStanding {
  playerId: string;
  name: string;
  avatarId: string;
  /** 名次，1 = 冠军；相同名次不会出现（服务器保证） */
  rank: number;
  /** 被淘汰的回合；冠军没被淘汰过，这里是 null */
  eliminatedRound: number | null;
  /** 结算时的血量（冠军是剩余血量，出局的恒为 0） */
  hp: number;
  wins: number;
  losses: number;
  level: number;
  /** 死亡那一刻场上的阵容（冠军 = 最后一回合的阵容）；**已按费用从低到高排序** */
  lineup: UnitPlacement[];
  /** 他激活的羁绊（只含已生效的） */
  traits: Array<{ traitId: string; count: number; activeAt: number }>;
  /** 本局他造成伤害最高的那一位干员（整局按 defId 汇总）；一点伤害都没有就是 null */
  topUnit: { defId: string; star: number; dealt: number } | null;
  /** 他这一局打出的总伤害（内部定点数，显示前 ÷FIX） */
  totalDamage: number;
}

export interface SubmittedTeam {
  /** 上场的棋子；`UnitPlacement.items` = 这枚棋子身上的 A 类藏品 */
  units: UnitPlacement[];
  /**
   * ★ 0.2 罗德岛：**跨回合叠层**（羁绊 id -> 已叠层数）。
   *
   * 和 `itemState.growth` 同性质 —— "这一局赢了几次"只有客户端那一局的状态知道，
   * 所以由客户端算、原样上报；战斗侧只负责把层数换成属性
   * （见 `rules.ts` 的 `roundTraitStack`）。
   *
   * ★ 服务端**必须在这一层放行**，否则会被静默丢掉 ——
   * `bench` / `itemState.bag` 都在这里踩过同一个坑（见 main.ts 那段注释）。
   */
  traitStacks?: Record<string, number>;
  /**
   * ★★ 0.2 MujicaAve：**fever（热度）** —— 跨回合的玩家资源。
   *
   * 【为什么也走"客户端算、服务器存"这条路？】
   * 和 `traitStacks` / `itemState` 完全同一个理由：攒了多少 fever 只有客户端
   * 那一局的状态知道（服务端没有"谁被打了多少下"的账本）。
   * 服务器只做三件事：**存**（重连时装回）、**夹**（`sanitizeFever`）、
   * **按它组阵容**（`feverSkillOf` → `TeamSetup.feverSkill`，两边必须算出同一份）。
   */
  fever?: FeverState;
  /** ★ 0.1.1：备战席（观战展示 + 淘汰回库都要用，见 BenchUnitView） */
  bench?: BenchUnitView[];
  /**
   * 共享装备位里的 B 类藏品 id（全队受益）。
   * 服务端不校验 —— 它和 `items` 一样只是"原始输入"，
   * 真正的加成永远由服务端拿它重算一遍。
   */
  sharedItems?: string[];
  /**
   * ★ 0.2：共享装备位里**每一件**藏品的成长层数（和 `sharedItems` 同下标）。
   *
   * 和 `units` 上的 `itemLayers` 是同一件事：同名藏品有多件时各叠各的。
   * ★ 新字段**必须在这里放行**，否则会被静默丢掉 —— 备战席 / `itemState.bag`
   *   都在这条路上踩过同一个坑。
   */
  sharedItemLayers?: number[];
  /**
   * 玩家的场外信息。
   *
   * 【金币】
   * 经济目前是客户端管的（见 `ClientMessage.playerStats` 那条注释），
   * 服务器手里没有账本，所以金币只能听客户端的。
   *
   * 【血量】
   * 这个服务器有权威值，所以 `Room.buildTeamSetup` **不采信**客户端上报的 hp，
   * 一律换成服务端自己的 `player.hp`。字段留着是为了格式统一。
   */
  playerContext?: { gold: number; hp: number };
  /**
   * ★ 0.1.1 藏品二版：客户端的「跨回合藏品状态」。
   *
   * `growth` = 每件藏品的成长层数（仇名录的击杀数 / 佣兵的饰物的胜场数…），
   * `unequipped` = 藏品栏里还没装载的藏品数量（悲伤的红按它加属性）。
   *
   * 【为什么让客户端算？】
   * 因为"上一场赢没赢、击倒了几个人、现在是第几回合"只存在于客户端那一局的状态里。
   * 和 `playerContext` 是同一个思路：客户端把结论交上来，服务端只负责喂给 createBattle。
   * 服务端会做一次范围夹取（见 main.ts 的 sanitizeItemState），但数值本身不重算。
   *
   * ★ 0.1.4：新增 `bag`（藏品栏本体）—— 断线重连时把"没装载的藏品"装回来
   *   （见 ItemBagSnapshot 的说明）。它是**第二次**出现"新字段漏在提交白名单里"的
   *   风险点，所以要一起进 `toTeamSetup`（本机预览）和联机提交这两条路。
   */
  itemState?: { growth?: Record<string, number>; unequipped?: number; bag?: ItemBagSnapshot };
}

export type ClientMessage =
  /**
   * 建一个新房间。
   *
   * ★ 0.1.3：多了 `version` —— 客户端自报家门，服务端**版本不一致就拒绝**。
   * 【为什么必须在服务端也拦一道？】
   * 客户端自己比对 `welcome.serverVersion` 只是"给自己提个醒"；
   * 老客户端（或者手动构造消息的人）照样能发请求。真正的不兼容
   * （协议字段变了、战斗内核算法变了）必须在服务端拦死，
   * 否则两边会对同一个局面算出不同结果 —— 联机里那是"莫名其妙打输/打赢"。
   */
  | { t: 'createRoom'; playerName: string; avatarId?: string; version?: string }
  /** 加入已有房间（`version` 同上） */
  | { t: 'joinRoom'; roomCode: string; playerName: string; avatarId?: string; version?: string }
  /** 离开房间 */
  | { t: 'leaveRoom' }
  /**
   * ★★ 0.3.2：**请求一份权威快照**（客户端发现自己的状态和服务器对不上了）。
   *
   * 【什么时候会发？】
   *   · `room.rev` 跳号（漏收了广播）—— 见 `RoomView.rev` 的说明；
   *   · 标签页从后台回到前台、或者刚从一次短暂的网络抖动里恢复。
   *
   * 【服务器怎么回？】**不发 `gameStarted`**（那会触发客户端做回合结算，
   * 补同步时再发钱就成了刷钱），只补四样"当前是什么状态"：
   * `room` + `pool` + `prepTeams` + `phaseState`。
   * 客户端拿 `phaseState` 对齐回合号与阶段，其余照常。
   */
  | { t: 'requestSync' }
  /**
   * ★ 0.1.2：**凭断线重连令牌换回座位**（断线重连的核心一步）。
   *
   * 【为什么必须由服务端裁决？】
   * "我是谁"这件事以前等于"我占着哪条 socket"（见 AGENTS.md 第 2.2 节）。
   * 现在身份变成一枚令牌：服务器查表把这条**新连接**接回**原来那个 playerId**
   * 与那个座位（血量、战绩、阵容全在），然后回一条 `resumeState` 全量快照。
   *
   * 【为什么用显式消息，而不是塞进 WebSocket 的 URL 参数？】
   * 两者都能做，但显式消息更好排错、也更好重试（失败可以隔一会儿再发一次）。
   * 而且服务端仍然先发 `welcome`（老客户端照旧工作），
   * 只是多了一条"我其实有令牌"的可选对话。
   *
   * 【失败会怎样？】回 `resumeFailed` —— 令牌过期、座位已被清掉、房间没了都会走它。
   * 客户端收到就退出重连状态、回主界面，并说明"这一局回不去了"。
   */
  | { t: 'resume'; token: string }
  /** 准备 / 取消准备 */
  | { t: 'setReady'; ready: boolean }
  /**
   * ★ 0.0.3 末：问服务器"局域网里现在有哪些房间"。
   * 用来把玩家输入的**房间号**换成"该连哪台机器"（见 LAN_BEACON_PORT 的说明）。
   */
  | { t: 'lanScan' }
  /**
   * ★ 上报"我的等级 / 连胜连败"（你报的第 11 条）。
   *
   * 【为什么要客户端上报？】
   * 因为**经济目前是客户端自己管的**（等级、连胜连败都是本地状态，
   * 见 docs「服务端权威经济」那条）。服务器要把它显示在玩家列表里，
   * 就只能让客户端在变化时告诉它一声。服务端只是**转发 + 展示**，
   * 不做任何校验 —— 这不是权威数据（血量那种才走服务端权威）。
   */
  | { t: 'playerStats'; level: number; streak: number }
  /** 房主开始游戏 */
  | { t: 'startGame' }
  /**
   * ★★ 0.3.5：**打完之后「再来一局」** —— 把房间退回大厅（座位不丢）。
   *
   * 【为什么不让客户端自己跳回大厅？】
   * "现在是什么阶段"是**房间级**的状态，只有服务器能改。
   * 客户端自己切到大厅视图，服务器那边还停在 `resolve / battle` ——
   * 房主点「开始游戏」会被拒（`canStart()` 看的是活人数），
   * 别人看到的还是"对局进行中"，两边就分家了。
   *
   * 【服务器做什么】见 `Room.backToLobby()`：血量、战绩、准备状态、盟约、
   * 阵容、牌库全部复位，然后把房间广播出去 —— 所有人一起回到同一个大厅。
   *
   * 【谁能发？】房间里任何人。一局已经打完了，谁都不想再盯着战绩页，
   * 让任意一个人把大家带回大厅是最顺手的（不需要等房主）。
   * 对局进行中发这条会被拒（`WRONG_PHASE`）—— 那等于"中途解散对局"，
   * 不该由一个玩家单方面决定。
   */
  | { t: 'backToLobby' }
  /**
   * ★ 0.1.1：房主把某个玩家请出房间。
   *
   * 【为什么必须由服务端裁决？】
   * 客户端点一下只是一个"请求"。真正要把人摘出 `room.players` /
   * `RoomManager.playerToRoom`、并且通知所有人大厅变了 —— 这些只有服务器做得到。
   * 权限（是不是房主）**也必须在服务端查**：客户端把按钮藏起来只是
   * "不给普通人看到"，不是权限控制（随便发一条消息就能绕过）。
   *
   * ★ 0.1.3：多了 `message` —— 房主可以写一句话，**原样显示给被踢的人**。
   * 可选；不写（或写完被清洗成空）就回退到默认文案「房主把你移出了房间」。
   */
  | { t: 'kickPlayer'; playerId: string; message?: string }
  /**
   * ★ 0.1.1：房主改某个玩家的昵称。
   * 昵称会被清洗（长度 + 字符白名单，见 shared/names.ts），服务器改完广播。
   */
  | { t: 'renamePlayer'; playerId: string; name: string }
  /**
   * ★★ 0.3：房主改**房间设置**（开局血量 / 开局金币 / 商店回合开关 / 布阵时长 / 每回合收入）。
   *
   * 【为什么只发"改了什么"，而不是整份设置？】
   * 因为整份发的话，"客户端以为的其余值"会覆盖服务端当前值 ——
   * 一旦有一端版本旧一点，就会莫名其妙回滚别人的设置。发 patch 更稳。
   *
   * 【权限和夹取都在服务端】
   *   · 只有房主能改（客户端藏按钮 ≠ 权限控制，随便发一条消息就能绕过）
   *   · 只有 `lobby` 阶段能改（开局后再改 = 有人按旧规则摆好了棋，规则却说变了）
   *   · 数值一律过 `clampRoomSettings` —— UI 上的 min/max 只是提示，不是防线
   */
  | { t: 'updateSettings'; settings: Partial<RoomSettings> }
  /**
   * ★★ 0.3.3：房主**往房间里加一台人机**。
   *
   * 【为什么需要一条专门的协议，而不让服务端自己塞一个假玩家？】
   * 因为"加不加、加几个、什么难度"是房主的决定，不是服务端的策略 ——
   * 服务端只负责：验权限、看还有没有空位、把人机**当成一个真玩家**建好座位。
   *
   * 【人机会不会成为一个"特权玩家"？】
   * 不会。人机在服务端就是一个普通的 `RoomPlayer` + 一条内部连接，
   * 它的每一步操作走的都是**和真人完全相同的消息**（买牌 / 提交阵容 / 选盟约…），
   * 同一套校验、同一套扣牌、同一套结算 —— 见 server/src/bot.ts。
   */
  | { t: 'addBot'; difficulty?: BotDifficulty }
  /**
   * ★★ 0.3.3：房主**移走一台人机**。
   * 只认 `bot:` 开头的 id（真人不能被这条路踢掉，那是 `kickPlayer` 的事）。
   */
  | { t: 'removeBot'; playerId: string }
  /**
   * ★★ 0.3.3：房主**改一台人机的难度**（"随时切换已有人机的难度"）。
   *
   * ★ 只在大厅阶段生效。开局之后改难度没有意义（这一局的种子、商店、
   *   经济全都定了），而且会让"刚才那几回合是简单、后面变成困难"这种
   *   说不清的战绩混进结算页。
   */
  | { t: 'setBotDifficulty'; playerId: string; difficulty: BotDifficulty }
  /**
   * ★★ 0.3：**藏品回复玩家生命**（消耗型：「应急补给」+5、「医疗包」+15 之类）。
   *
   * 【为什么必须单独发一条？】
   * 联机里玩家血量是**服务端权威**的（`RoomPlayer.hp`），客户端只是显示。
   * 以前这种藏品是客户端自己 `economy.hp += N` —— 下一次房间广播就把这几点抹掉了，
   * 表现就是"说明写着回血，装了没反应"（用户在多人模式里报的 bug）。
   *
   * 【服务端怎么处理】只认一个"加多少"，自己夹范围（不能超过开局血量上限），
   * 加完广播。★ 它和金币一样属于"客户端说、服务端信"的过渡做法，
   * 等 0.4 的服务端账本（反作弊 B）落地后要一起收编。
   */
  | { t: 'healPlayer'; amount: number }
  /**
   * ★★ 0.3：盟约选秀里"我选这个"。
   *
   * 【服务端会验三件事】现在是不是轮到你 / 这个盟约存不存在 / 有没有被别人选走。
   * 一条都不满足就回错，不改任何状态 —— "先点的人赢"就是在这儿保证的。
   */
  | { t: 'pickCovenant'; covenantId: string }
  /** 提交本回合的阵容（准备阶段每次改动后静默同步，见 syncTeamToServer） */
  | ({ t: 'submitTeam' } & SubmittedTeam)
  /**
   * 买下商店里的某个棋子。
   *
   * 【为什么买卖要问服务器？】
   * 因为牌库是**全房间共享**的：1 费每张牌整局只有 27 张，
   * 8 个人在抢同一批。如果每个客户端自己扣自己的牌库，
   * 就会出现"三个人同时买到同一张牌的最后一张" —— 牌库凭空变多。
   * 所以"扣牌"这件事必须由服务器裁决，客户端只能申请。
   *
   * 注意：**金币目前仍然是客户端自己管的**（见 docs 里"服务端权威经济"那条），
   * 所以这里只保证"牌不会超发"，不保证"钱够不够"。
   */
  /**
   * ★ 0.2：`count` = 一次扣几张（商店回合的干员位卖的是 **2 星 = 3 张**，
   * 所以必须能一次扣 3 张 —— 分 3 条消息发的话，中间可能被人抢光，
   * 于是出现"扣了 2 张却给了个 2 星"这种牌库超发）。
   * 不传 = 1 张（常规商店那一格一张）。
   */
  | { t: 'buyCard'; defId: string; count?: number }
  /**
   * ★ 0.1.1：藏品「随机招募」（人事部铜印 / 博士银印）申请一次招募。
   *
   * 【为什么也要服务器裁决？】
   * 和买牌同一个理由：招募到的干员**真的占牌库 1 张**，
   * 而牌库是 8 个人共享的 —— 客户端自己扣就会出现"多人各招一只、牌库超发"。
   * 服务器按 `seed` 复现"该招到谁"（规则在 shared 的 `pickRecruit`，单机同一套），
   * 顺手把那张牌扣掉；该费用区间已经空了就回一份金币补偿。
   *
   * 注意：装备这件藏品本身（销毁 / 占格子）仍是客户端做的 ——
   * 服务器只裁决"牌库这一件事"（和金库/血量的口径一致）。
   */
  | {
      t: 'recruitFromPool';
      /** 费用区间（含边界）：铜印 1~3、银印 4~5 */
      minCost: number;
      maxCost: number;
      /** 随机种子：客户端给，服务器照它复现同一次抽取 */
      seed: number;
    }
  /** 卖掉一个棋子：按星级把牌还给牌库（二星还 3 张、三星还 9 张） */
  | {
      t: 'sellCard';
      defId: string;
      star: number;
      /**
       * ★ 0.0.3：这次卖**该还牌库几张**。
       *
       * 【为什么不直接按星级算？】
       * 因为道具多给的份数没从牌库拿过：博士投影把 1★ 升到 2★ 之后，
       * 这只只占 1 张牌库 —— 卖掉时按星级还 3 张，牌库就会凭空多出 2 张。
       * 不带这个字段时服务端退回"按星级算"（老客户端兼容）。
       */
      copies?: number;
    }
  /**
   * ★ 我的商店里现在摆着哪些棋子（每次刷新/买走之后发一次）。
   *
   * 【为什么要告诉服务器？—— 它修的是"两个人刷出同一张牌"】
   * 牌库里只剩 1 张的棋子，如果同时挂在两个人的商店里，
   * 那就是"两个人抢一张牌，先点的人赢" —— 但另一边的玩家会看到
   * 一张**点了就报错**的卡片，只会觉得游戏坏了。
   * 所以摆在我商店里的牌要先"预定"下来：
   * 别人刷新时不会再抽到它，直到我刷新商店（或者买走）把它放回池子。
   *
   * 只发 defId 就够了 —— 服务器不关心它摆在第几格、卖多少钱，
   * 只关心"这几张牌现在被谁占着"。
   */
  | { t: 'shopUpdate'; defIds: string[] }
  /**
   * 客户端本地重放后，发现校验和与服务器不一致，上报给服务器。
   *
   * 这是抓「确定性 bug」最有效的手段：一旦有人在真实环境里踩到，
   * 服务器日志里就会留下具体是哪颗种子、哪场战斗、差多少 ——
   * 而不是等玩家抱怨「我这边明明赢了」时才发现。
   */
  | { t: 'checksumMismatch'; battleId: string; expected: number; actual: number }
  /**
   * ★ 我这边把这场战斗的回放**播完了**。
   *
   * 【为什么需要这条消息？—— 它修的是"战斗被跳过 / 双端不同步"】
   * 服务器以前是这样决定下一回合的：拿到这场战斗打了多少 tick，
   * 换算出秒数，`setTimeout` 等这么久就广播下一回合。
   *
   * 这套算法有个致命前提：**客户端的回放必须和墙钟一样快**。而它不是：
   *   · 客户端主循环把单帧步长 cap 在 0.05 秒（防止切标签页回来瞬间播完），
   *     所以帧率一旦低于 20fps，回放就比墙钟**慢**；
   *   · 棋盘上 20 个棋子 + 技能特效，弱电脑掉到 15fps 很常见；
   *   · 切出去看一眼别的窗口，回放直接停住。
   * 于是服务器"以为大家都看完了"的时候，慢的那台还在打 ——
   * 下一回合的 `gameStarted` 一到，客户端 `replay.clear()`，
   * 战斗就被**从中间擦掉**：玩家看到的是"直接跳过战斗过程"。
   *
   * 现在改成：服务器**等参战双方的这条回执**，收齐了才进下一回合
   * （同时保留一个兜底超时，防止有人挂机把房间卡死）。
   * 这样"快的人"会等"慢的人"，两边看到的东西就一致了。
   */
  | { t: 'playbackDone'; battleId: string }
  /**
   * ★ 0.1.4：**投票「取消暂停」**（暂停浮层上那颗唯一的「同意」按钮）。
   *
   * 【规则】暂停期间，**在线的人**全部点了同意 -> 暂停立刻取消，
   * 掉线那位当场被淘汰（他本人点不了，所以不要求他）。
   * 暂停浮层上只有这一个按钮 —— 没有"再等等"，要么等满时限（3 分钟，到点也是淘汰）。
   */
  | { t: 'pauseVote' }
  /** 心跳，用来检测掉线 */
  | { t: 'ping' };


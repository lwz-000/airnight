export interface RoomView {
  code: string;
  hostId: string;
  /** 房间状态机：等待 -> 准备阶段 -> 战斗中 -> 结算 -> 等待 */
  /** ★ 0.2：`shop` = 商店回合（野怪回合之后插入的 90 秒，结束后回 `prep`） */
  phase: RoomPhase;
  round: number;
  players: PlayerView[];
  /** 准备阶段剩余秒数 */
  prepSecondsLeft: number;
  /**
   * ★ 0.1.3：对局是不是**暂停**了（在线玩家不足 2 人）。
   *
   * 用来让界面说清楚"现在在等什么"——
   * 不然玩家只会看到一个不动的倒计时，以为游戏卡死了。
   *
   * ★ 0.1.4：判据从"在线不足 2 人"放宽成"**只要有还活着的玩家掉线**就暂停"，
   * 并且暂停有明确时限（3 分钟）。下面几个字段就是给暂停浮层用的。
   */
  paused?: boolean;
  /** 暂停还剩几秒（到点掉线的人被淘汰、对局继续） */
  pauseSecondsLeft?: number;
  /** 已经有几个人点了「同意」 */
  pauseVoteCount?: number;
  /** 需要几个人同意（暂停那一刻**在线**的人数） */
  pauseVoteNeeded?: number;
  /**
   * ★★ 0.3：这一局的规则（房主在等待界面 DIY 的那份）。
   *
   * 【为什么要广播给所有人，而不是只给房主？】
   * 因为"开局血量 5000""布阵 500 秒"这些必须**所有人**看到同一份 ——
   * 否则房主眼里是 5000 血，别人眼里还是 100 血，倒计时也对不上。
   * 它是**服务端下发**的，客户端只照着显示，不参与计算（见 room-settings.ts）。
   */
  settings: RoomSettings;
  /** ★★ 0.3：盟约选秀进度；`phase !== 'covenant'` 时不存在 */
  covenant?: CovenantDraftView;
  /**
   * ★★ 0.3.2：这份房间视图的**修订号**（服务端每广播一次 +1）。
   *
   * 【为什么需要它？】
   * 房间状态是一条一条增量推下来的（`room` / `pool` / `prepTeams` / `gameStarted`…）。
   * 网络抖一下、标签页被浏览器冻住一会儿，客户端就可能**漏收**其中几条 ——
   * 于是"我还停在第 6 回合，别人已经在第 8 回合开打了"（用户说的"平行世界"）。
   * 光靠每秒重播是补不回来的：重播的是**最新**状态，而客户端缺的是"那一跳"。
   *
   * 有了修订号，客户端能立刻发现"我漏了一份"（`rev` 跳号），
   * 然后主动发 `requestSync` 让服务器补一份权威快照。
   * 老客户端不读它也不会坏（可选字段）。
   */
  rev?: number;
}

/**
 * 一场战斗的广播载荷（`battleStart`）。
 *
 * 【注意这里传了什么 —— 这是自走棋联机的精髓】
 * 只传 seed（一个数字）+ 双方阵容 + 单位名字。
 * 客户端拿到后本地跑一遍 simulate()，就能演出完全一样的战斗。
 * 所以战斗期间不需要同步任何实时数据，流量几乎为零。
 *
 * ★ 0.1.2：把它抽成**具名类型**，因为断线重连要对它做两件新事：
 *   · 服务端把这一回合每一场的这份载荷**缓存**下来（`battleCache`）；
 *   · 战斗中重连的人通过 `resumeState.battles` 一次性补收，逐条重放。
 * 抽出来之后"重放"和"实时广播"走的是同一个形状 —— 客户端只有一条处理路径。
 */
export interface BattleStartPayload {
  t: 'battleStart';
  battleId: string;
  seed: number;
  team0: TeamSetup;
  team1: TeamSetup;
  /**
   * 这两场对战的双方玩家 id。
   *
   * 【为什么必须带上？】
   * 原因一：客户端要判断「这场战斗有没有我」。
   *   房间里 6 个人会同时收到 3 场战斗的广播，
   *   每个人的客户端只应该演自己那一场。
   * 原因二：客户端要知道「我在左边还是右边」。
   *   玩家永远希望自己的棋子在画面左下角。
   *   如果你被分到了 team1，客户端就要把整个战场左右翻转显示。
   */
  team0PlayerId: string;
  team1PlayerId: string;
  /**
   * ★ 0.0.2 追加：这一场是不是「影子对战」（奇数人的轮空者打的复制阵容）。
   *
   * 值是**被复制的那位玩家的名字**（客户端显示成「VS 影·某某」）。
   *
   * 【为什么轮空者要打影子？】
   * 人数是奇数时总得有人轮空。原来轮空 = 干看着别人打、什么都不发生，
   * 玩家干等一回合。现在让轮空者跟「某个存活玩家的阵容复制品」打一场：
   * 输了一样扣自己的血，但**被复制的那位一点影响都没有**
   * （不掉血、不计胜负）—— 他只是在不知情的情况下当了回陪练。
   *
   * 【为什么 team1PlayerId 是一个假的 id？】
   * 影子不是真人，不能填任何真实玩家的 id ——
   * 否则那个人会以为"这场有我在打"，视角/结算全乱。
   * 所以 team1PlayerId 固定是 `'ghost'`，客户端靠本字段识别影子。
   */
  ghostOf?: string;
  /**
   * ★ 0.0.3 追加：这一场是不是「野怪回合」（对手是一波野怪）。
   *
   * 值是这一波野怪的一行人话描述（客户端显示成「VS 野怪 · 源石虫」）。
   * 和 ghostOf 一样，识别方式是 `team1PlayerId === MONSTER_PLAYER_ID`。
   */
  monsterWave?: string;
  /**
   * ★ 0.1.1 追加：这一场里用了「阵容丢失保底」的玩家 id（可能是 0、1、2 个）。
   *
   * 【什么是保底？】
   * 偶尔会出客户端手里的牌莫名消失（多为网络/同步抖动），
   * 于是报到服务器的是**空阵容**，玩家什么也打不了。
   * 服务器因此保留每个人"本回合最近一次有效的阵容"：
   * 一旦发现当前这份是空的，就用那份顶上，并在本字段里说明是谁用了兜底，
   * 客户端据此提示玩家「你的阵容刚才丢失，已用最近一次的阵容参战」。
   */
  safetyNetFor?: string[];
  /** 单位 id -> 显示名，方便客户端字幕/血条显示 */
  names: Record<number, string>;
  /** 服务器算出的权威校验和，客户端算完后比对，不一致就上报 */
  expectedChecksum: number;
}

/**
 * ★ 0.1.2：断线重连成功后服务器下发的**全量快照**。
 *
 * 【为什么必须是"全量"？】
 * 现在的广播全是**增量事件**（`room` / `pool` / `prepTeams` / `battleStart`…），
 * 掉线期间的事件服务器不缓存也不补发（见 AGENTS.md 第 2.5 节）。
 * 所以重连的人不能靠"等下一批事件"回到现场 —— 必须有人把**当前状态**整体告诉他。
 * 这一条消息就干这件事：客户端拿它重建房间、牌库、观战阵容和"我该看的那一场"。
 */
export interface ResumeStatePayload {
  t: 'resumeState';
  /** ★ 换回的**原** playerId（不是这次连接临时分配的那个） */
  playerId: string;
  serverVersion: string;
  room: RoomView;
  /** 牌库：还剩几张 + 谁占着哪几张（和 `pool` 广播同形状） */
  pool: { remaining: Record<string, number>; held: Record<string, string[]> };
  /** 所有人本回合摆好的阵容（和 `prepTeams` 同形状） */
  prepTeams: Record<string, PrepTeamView>;
  /**
   * 我本回合最后一次同步给服务器的阵容（服务端手上最完整的"我"）：
   * 上场棋子（含 A 类藏品）、备战席、共享装备位、`playerContext`（金币/血量）、`itemState`。
   *
   * 【为什么把金币也带上？】金币本来是客户端管的（服务端没有账本），
   * 但 `submitTeam` 里客户端**主动上报**过它 —— 所以服务端手里其实有一份滞后副本。
   * 刷新页面之后本地状态全丢了，用这份副本能至少把经济恢复到"上次同步的那一刻"。
   */
  myTeam: SubmittedTeam | null;
  /** 服务端当前阶段（客户端据此决定是回到布阵还是继续看战斗） */
  phase: RoomView['phase'];
  round: number;
  prepSecondsLeft: number;
  /** ★ 0.2：商店阶段还剩几秒（不在商店阶段就是 0） */
  shopSecondsLeft?: number;
  /**
   * ★ 这一回合正在播的战斗（战斗中重连时用它重放；不在战斗阶段就是空数组）。
   *
   * 【为什么要带 `elapsedMs`？】
   * 服务端知道这场战斗是**什么时候**开始广播的，客户端不知道 ——
   * 不带的话重连者只能从第 0 秒重放，而别人已经看到第 N 秒了，
   * 观战进度就永远对不上。`elapsedMs` 由服务端算（"现在 - 广播时刻"），
   * 所以**不受两台机器时钟差影响**。
   */
  battles: Array<{ battle: BattleStartPayload; elapsedMs: number }>;
  /** 我是不是已经被淘汰了（淘汰者重连回来只能观战） */
  eliminated: boolean;
}


/**
 * 布阵阶段时长（秒）。你要求 60 秒。
 *
 * 【注意：不再是"倒计时结束才开始"了】
 * 现在布阵是**定时制**：时间一到，服务器拿每个人当前摆好的阵容自动开打，
 * 玩家不需要点"提交阵容"（那个按钮已经删掉了）。
 * 客户端每改一次阵容就会静默同步给服务器，所以 60 秒结束时
 * 服务器手里的就是最新的一份。
 */
export const PREP_SECONDS = 60;

/**
 * ★ 0.1.3：**前几回合用短布阵**。
 *
 * 【为什么开头要短？】
 * 开局那几回合每个人手里就一两张牌，摆两下就完事了 ——
 * 让他们对着一个 60 秒的倒计时干等，是纯粹的浪费。
 * 从第 4 回合起牌多了、要算羁绊和站位，才需要完整的 60 秒。
 *
 * 【为什么规则放在 shared？】
 * 界面上的提示文案（"布阵 30 秒"）和服务器真正等的秒数必须是**同一个数**，
 * 两边各写一条 `round <= 3` 迟早会走散（一个说 30 秒、实际等 60 秒）。
 */
export const EARLY_ROUND_COUNT = 3;
export const EARLY_PREP_SECONDS = 30;

/**
 * 某个回合的布阵时长（秒）。
 *
 * 规则：**前 3 回合固定 30 秒**；之后用 `customPrepSeconds`（房间设置里的值），
 * 不传就是默认的 60 秒。
 *
 * ★ 0.3：多了一个 `customPrepSeconds` 参数（房间设置）。为什么**前 3 回合不让自定义**？
 *   因为开局那几回合手上只有一两张牌，摆两下就完了 —— 房主就算把布阵设成 500 秒，
 *   前 3 回合也不该跟着变成 500 秒（那是干等）。这条规则只在这里实现一次，
 *   服务端、客户端文案都走它。
 *
 * @param customPrepSeconds 第 4 回合起的布阵时长；不传 = `PREP_SECONDS`
 */
export function prepSecondsForRound(round: number, customPrepSeconds = PREP_SECONDS): number {
  if (round <= EARLY_ROUND_COUNT) return EARLY_PREP_SECONDS;
  /*
    夹一下：房主理论上能塞进来 0 或负数（服务端已经夹过一遍了，但这是个纯函数，
    谁都能调）。下界给 5 秒是因为"0 秒布阵"会让客户端连一帧都来不及摆。
  */
  const seconds = Math.round(Number(customPrepSeconds));
  return Number.isFinite(seconds) && seconds > 0 ? Math.max(5, seconds) : PREP_SECONDS;
}

/**
 * 布阵最后几秒**不显示其他玩家的血量**。
 *
 * 【为什么要藏？】
 * 血量是"谁快出局了"的信号。最后一刻还能看到的话，
 * 可以针对性地决定"这回合要不要梭哈"（反正有人比你更危险），
 * 变成一个纯信息优势。藏掉之后最后 5 秒只能靠自己判断。
 */
export const BLIND_HP_LAST_SECONDS = 5;

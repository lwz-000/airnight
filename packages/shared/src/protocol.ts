/**
 * ============================================================
 *  联机协议 —— 客户端和服务器之间说好的「暗号」
 * ============================================================
 *
 * 【这份文件为什么重要？】
 * 联机 bug 的一大来源是「两边对消息格式的理解不一致」。
 * 所以协议集中定义在这一个文件里，前后端都 import 它。
 * 谁改了字段，另一边的类型检查立刻就会报错 —— 而不是等上线后才炸。
 *
 * 【消息流动方式】
 *   客户端 --ClientMessage--> 服务器 --ServerMessage--> 所有客户端
 *
 * 每条消息都有一个 t 字段表示类型（type）。
 * 加了新功能就在下面两个联合类型里加一种，然后 TypeScript 会告诉你
 * 哪些地方需要补处理逻辑（这叫「穷尽性检查」，是白捡的保险）。
 */


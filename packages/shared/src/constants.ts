/**
 * 全局常量。
 *
 * 【为什么数值都这么大？】
 * 自走棋要联机，就必须保证「同一场战斗，在你的电脑和朋友的电脑上算出完全一样的结果」。
 * 这叫「确定性」。而小数（fraction / float）在不同 CPU、不同浏览器上算出来的最后几位
 * 可能不一样 —— 单次看不出来，但一场战斗要算上千次，误差会累积成「我这边赢了、你那边输了」。
 *
 * 解决办法：全程用「整数」运算。
 *   - 想要 1.5 秒，就存 1500 毫秒（单位：毫秒）
 *   - 想要 550.5 点血，就存 550500（单位：千分之一）
 *   - 想要 25% 加成，就存 2500（单位：万分之一，叫 basis point / bp）
 *
 * 所有除法都用 Math.floor 向下取整，保证跨平台完全一致。
 * 这个文件定义的 FIX / BP 就是这套「放大倍数」的开关，改这里就能调精度。
 */

/** 定点数放大倍数：1 点 = 1000 个整数单位。用于血量、伤害、距离等 */
export const FIX = 1000;

/** 万分比放大倍数：100% = 10000 bp。用于各种倍率、加成、减免 */
export const BP = 10000;

/** 战斗逻辑频率：每秒推进多少个 tick（逻辑帧） */
export const TICKS_PER_SECOND = 20;

/** 一场战斗最多持续多少 tick，超过就按血量判定（防止双方互相打不死而卡死） */
export const MAX_BATTLE_TICKS = 20 * 75; // 75 秒

/**
 * ============================================================
 *  ★ 战斗时长规则（你要求的第 14 条）
 * ============================================================
 *
 * 【为什么需要？】
 * 双方都有治疗/护盾/免伤时，一回合能互相磨到 75 秒上限 ——
 * 玩家盯着一场"谁也打不死谁"的战斗看一分多钟，体验很差。
 * 所以加两道闸门，把长尾战斗强行收束：
 *
 *   40 秒（RAGE_START_TICKS）：**全场狂暴**。
 *     所有存活干员的攻击力和攻速大幅提升 —— 血线开始哗哗掉，
 *     磨不下去的僵局会在这段时间里分出胜负。
 *     做成"全场一起狂暴"而不是"只给某一方"，是为了不改变胜负关系：
 *     它只是把剩下的时间加速，不会凭空扶植劣势方。
 *
 *   70 秒（FORCE_END_TICKS）：**强制结束**。
 *     按"当前存活干员多的一方"获胜；数量一样再比剩余总血量。
 *     注意是比**存活数量**而不是血量百分比 —— 场上多站一个人，
 *     本来就意味着更大的胜面，这比"谁血条长"更符合直觉。
 */
export const RAGE_START_TICKS = 20 * 40; // 40 秒
export const FORCE_END_TICKS = 20 * 70; // 70 秒

/** 狂暴期给的攻击力加成（万分比）：+150% */
export const RAGE_ATTACK_BP = 15000;

/** 狂暴期给的攻速加成（万分比）：+100% */
export const RAGE_SPEED_BP = 10000;


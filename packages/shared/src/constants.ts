/**
 * ★ 0.2：**受击回复**每挨一次打回复多少法力 —— 固定值，和挨了多少伤害无关。
 *
 * 【为什么从"按伤害算"改成固定？】
 * 用户口径：「将受击回复从根据伤害计算回复数值改为固定值100」。
 * 老做法是 `伤害 × 万分比`（物理 20 / 法术 8），后果是**伤害量决定充能速度**：
 *   · 被小怪刮一下几乎不涨；被 Boss 砸一下直接回一大截；
 *   · 物理/法术还要分档，玩家在详情页根本算不出"我还差几下能开技能"。
 * 改成固定 100 之后，`MANA_MAX = 1000` ⇒ **挨 10 次打必定开一次技能**，
 * 和「每次普攻回 100」是同一套读法，两种回复方式完全对称、也好跟玩家解释。
 */
export const MANA_FROM_DAMAGE_TAKEN = 100;

/**
 * ★ 0.2 羁绊「不屈」：**每复活成功一次，下一次复活的概率降多少**（万分比）。
 *
 * 用户口径：「改成每次死都掷，但是加一个限制，每复活一次复活概率 -10%」。
 * 减的是**百分点**（1000 bp = 10%），不是"乘 0.9" ——
 * 和项目里"+20% 攻速"= `2000` 是同一套读法。
 *
 * ⇒ 三档的实际上限：
 *   · 2 人（30%）：30% → 20% → 10% → 0%（最多站起来 3 次）
 *   · 3 人（40%）：40% → 30% → 20% → 10% → 0%（4 次）
 *   · 5 人（50%）：50% → 40% → 30% → 20% → 10% → 0%（5 次）
 * 概率降到 0 之后就不再掷骰（也不会白耗一次随机数）。
 */
export const UNYIELDING_CHANCE_DECAY_BP = 1000;


/**
 * ============================================================
 *  ★★ 0.2 商店回合：**出现时机 + 时长**
 * ============================================================
 *
 * 【★ 为什么这两个数必须住在 shared，而不是只在客户端？】
 * 商店回合在**联机**里是服务端的一段真实阶段（服务端要先开 90 秒商店、
 * 再开正常布阵），客户端只是跟着显示。
 * 两边各写一份判据的下场一定是"某一边认为有商店、另一边认为没有"：
 *   · 服务端开了商店、客户端没进  -> 玩家看不到商店，但那 90 秒白白等掉了；
 *   · 客户端进了商店、服务端没开  -> 商店弹到一半就开战，货没买成。
 * 所以「什么时候有商店回合、它有多长」只在**这一处**实现，两边都 import 它。
 *
 * 【用户口径】
 *   · 在**野怪回合之后**出现，**第 1、2 回合不算**；
 *   · **不计入回合数**（它不是一个回合，只是回合之间的插曲）；
 *   · **独立阶段**，持续 **90 秒**。
 */
import { isMonsterRound } from './monster-data.js';

/** 商店回合持续多少秒（用户口径：90 秒） */
export const SHOP_ROUND_SECONDS = 90;

/**
 * ★ 0.2：本局的**第一次**商店回合出现在第几回合之后（野怪回合 9 之后）。
 *
 * 【为什么要这个常量？】失落之钥"只在本局第一次商店出现"，判"是不是第一次"
 * 用 `shopRoundCount` 就够 —— 但那是本地计数，**重连重建 state 之后会归 0**。
 * 所以再拿回合号兜一道底：正常对局一定从第 1 回合开始，
 * "回合号 > 9"时玩家必然已经过了第一次商店的机会，不该再当成第一次。
 */
export const FIRST_SHOP_ROUND = 9;

/**
 * 这个回合打完之后要不要进商店回合。
 *
 * 野怪回合的节奏是 1、2、9、16、23…（见 `isMonsterRound`），
 * 扣掉"不算"的第 1、2 个 ⇒ 实际出现在 **9 / 16 / 23 / 30 / 37 / 44** 回合之后。
 *
 * ★ 传进来的必须是**刚刚结算完的那个回合号**（服务端在 `beginRound()` 自增之前读它）。
 */
export function isShopRoundAfter(round: number): boolean {
  if (!isMonsterRound(round)) return false;
  return Math.floor(round) >= 9;
}

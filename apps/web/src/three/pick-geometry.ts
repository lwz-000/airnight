/**
 * ============================================================
 *  拾取几何：判断"这一次点击究竟算不算点在这枚棋子上"
 * ============================================================
 *
 * 从 board.ts 里抽出来的**纯规则**（只有算术，没有 WebGL / 没有场景树），
 * 所以可以在 Node 里跑单元测试 —— 和 game/grid.ts 里的坐标数学一个待遇。
 *
 * 【为什么需要它？（你报的"放置和选择红方时有概率鼠标偏移"）】
 * 棋子是一张永远面朝相机的 billboard。它的四边形**不等于**它脚下那一格：
 *   · 小人素材的画布可以宽到 2.58 格（野怪 `mn_jakill` 是 448×278），
 *     人形干员也普遍到 1.3 格宽；
 *   · 于是「射线从上往下扫，第一个命中的棋子」这种朴素做法，
 *     会变成"点在 A 格、打中的却是隔壁 B 格那个怪"。
 *
 * 【解法：看"射线打在棋盘上的落点"，而不是"射线打中谁"】
 * 把射线和**卡片中心高度那一层的水平面**（y = CARD_CENTER_Y）求交，
 * 得到的落点无论你点卡片哪个部位，都稳稳落在"这枚棋子站着的那一格"里。
 * 落点离这枚棋子的中心横竖都不超过 {@link PICK_RADIUS} 才算数。
 *
 * 【为什么不是 0.5（正好半格）？—— 实测出来的数】
 * 卡片是**斜立着**的 billboard（相机俯角约 78°），它的"顶端"在世界里
 * 其实偏向**远离相机**那一侧（相机上方向 ≈ (0, 0.21, -0.98)）。
 * 所以你点卡片顶端/角上时，射线落点会越过这一格的边界、往后面那格探出去一点。
 * 实测（见 test/pick-geometry.test.ts，扫了全部窗口比例 × 最远/最近两种视角）：
 *   · 默认视角（最远，距离约 15.7）：最坏 0.525 格
 *   · **拉到最近（MAX_ZOOM_IN = 2，距离约 7.8）：最坏 0.566 格** ← 真正的上界
 *     （出现在棋盘角上的格子、点卡片角的时候）
 * 所以 0.5 会把"点自己干员的脑袋/卡片角"判成非法（点击落到后面那格去），
 * 必须留出余量。取 0.6 ≈ 0.566 再留 6%：
 *   · 合法点击（卡片上任意位置）全部通过；
 *   · 隔壁那一格的中心离本棋子 1.0 格，远在 0.6 之外 —— 你报的偏移照样被挡掉。
 * 代价是"隔壁格子最外沿 0.1 格"这一段会被本棋子接走，但那段正好是卡片
 * 视觉上确实探过去的部分（外凸 0.03~0.07 格），所以看画面是对的。
 *
 * 【这几个数是钉住的】test/pick-geometry.test.ts 会重新量一遍；
 * 谁动了相机俯角 / 卡片尺寸 / 这个常数，测试马上会红。
 */

/** 落点离棋子中心多远还算"点在自己这一格"。单位：格（1 = 一格） */
export const PICK_RADIUS = 0.6;

/** 平面落点（只用得上 x / z，故意不依赖 Three.js 的 Vector3） */
export interface PlaneHit {
  x: number;
  z: number;
}

/**
 * 射线与水平面的落点，是否落在「这枚棋子自己那一格」里。
 *
 * @param hit     射线与水平面的交点；`null` = 打不到平面
 * @param centerX 棋子中心的世界 x
 * @param centerZ 棋子中心的世界 z
 *
 * 【打不到平面时返回 true（放行）】
 * 射线朝上、与平面平行/背向时求交会失败。这只可能发生在相机被拖到很怪的角度、
 * 或者棋盘整个跑到视线外的时候 —— 那种情况下宁可"像以前一样让它打中"，
 * 也不要凭空让点击失效（否则玩家会觉得"点了没反应"）。
 */
export function pickHitsOwnCell(hit: PlaneHit | null, centerX: number, centerZ: number): boolean {
  if (hit === null) return true;
  return Math.abs(hit.x - centerX) <= PICK_RADIUS && Math.abs(hit.z - centerZ) <= PICK_RADIUS;
}

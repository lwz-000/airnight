export const CHIBI_FOOT_SCREEN = 0.875;

/**
 * ============================================================
 *  ★ 棋子（卡片 / 小人）在棋盘上的**中心高度**（世界单位）
 * ============================================================
 *
 * 【为什么必须只有这一份？】
 * 布阵棋子（main.ts）、战斗演出（replay.ts）把精灵摆到这个高度；
 * 而**鼠标拾取**（board.ts 的 screenToCell）也要用同一个高度 ——
 * 拾取是拿"射线打在这一层平面上的落点"来判断"你点的是哪一格"的。
 * 两边一旦不是同一个数，"卡片画在这个高度、拾取按那个高度算"就会错位，
 * 表现出来正是那种说不清的"鼠标偏移"。
 *
 * 【数值怎么来的？】
 * 卡片世界高 0.96（CARD_WORLD_SCALE.y），立在地板上再抬一点看起来才有厚度，
 * 所以中心取 0.42（≈ 半高 0.48 减一点）。
 */
export const CARD_CENTER_Y = 0.42;

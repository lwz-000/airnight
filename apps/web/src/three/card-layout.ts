/**
 * ============================================================
 *  棋子卡片的版式常量（唯一来源）
 * ============================================================
 *
 * 【为什么单独放一个文件？】
 * 卡片是这样两层叠出来的：
 *
 *   · 底层是一张 canvas 画出来的卡片贴图（three/sprite-graphics.ts）
 *   · 上层是 Q 版小人精灵（three/chibi.ts），挂在卡片精灵的**子节点**上
 *
 * 小人要摆进卡片里的"立绘框"，就必须知道这个框在哪、多大、卡片本身多大。
 * 这两个文件互相 import 的话会形成循环依赖，ESM 下会踩到"模块还没执行完，
 * 常量还是 undefined"的 TDZ 坑。所以把这些纯数字抽到这个**不依赖任何模块**的
 * 叶子文件里，两边都从这里读 —— 数字只有一个来源，改一处两边同时生效。
 */

/** 卡片画布尺寸（像素）。宽高比 3:4，接近角色立绘 */
export const CARD_W = 192;
export const CARD_H = 256;

/**
 * 卡片在**世界里**的尺寸（世界单位），也就是卡片精灵自身的 scale。
 *
 * chibi.ts 挂的是子节点，子节点的 scale 会再乘一次父节点的 scale，
 * 所以它必须知道父节点缩放是多少，才能反推出"自己该写多少"。
 */
export const CARD_WORLD_SCALE = { x: 0.72, y: 0.96 };

/** 卡片里"立绘区"的像素范围（左上角为原点、y 向下） */
export const PORTRAIT_AREA = { x: 6, y: 6, w: CARD_W - 12, h: Math.round(CARD_H * 0.56) };

/**
 * ============================================================
 *  ★ 渲染层级（0.0.2：星级要"置顶"）
 * ============================================================
 *
 * 卡片 / 小人 / 血条 / 星级是**四张平级的精灵**（后三个挂在卡片下，但深度排序按对象算）。
 * three.js 对透明物体是**先比 renderOrder、再比投影后的深度**，
 * 只靠 z 在斜视角下很容易算错，所以这里把层级写死成一份，谁都从这里读。
 *
 *   0 卡片底面  →  1 Q 版小人  →  2 血条  →  3 星级
 *
 * 【为什么星级在最上面？】
 * 小人被刻意往前推了一点（DEPTH_EPSILON）专门用来盖住卡面的大色块，
 * 于是"星级画在卡面贴图里"就一定会被小人的头肩挡住 ——
 * 三星的棋子看起来和两星没区别。把星级单独抽成一张精灵、
 * 层级压在所有东西之上，才能保证"一眼看出这是几星"。
 *
 * 放在这个叶子文件里（而不是各自的模块里）是为了避免循环依赖：
 * sprite-graphics.ts 和 chibi.ts 都 import 它，它不 import 任何人。
 */
export const RENDER_ORDER_CARD = 0;
export const RENDER_ORDER_CHIBI = 1;
export const RENDER_ORDER_HP = 2;
/**
 * ★ 0.1.4：技能条和血条**同一层**。
 *
 * 两条是上下并排的（技能条在血条正下方），互不遮挡；
 * 只要比小人高就行，没必要再插一层 —— 层级越少，"谁压谁"越不容易算错。
 */
export const RENDER_ORDER_SKILL_BAR = 2;
export const RENDER_ORDER_STARS = 3;

/**
 * ★★ 0.2：**棋子特效**这一层 —— 所有棋子精灵（0~3）之上。
 *
 * 【为什么需要专门一层？】锏的「疯狂斩击」是以**它自己脚下**为圆心、
 * 半径 1~2 格的一圈刀光。棋子的卡面是一张 0.96 世界单位高的公告板，
 * 站在同一格上 —— 刀光和外圈的棋子精灵在**投影后几乎同一个深度**，
 * 而它和卡面一样是 `depthWrite: false` 的透明物体（depthWrite 关掉之后
 * 深度测试根本不参与"谁压谁"）。于是 three.js 只能按"离相机的距离"排序，
 * 结果就是**随机地一半被敌怪/干员的卡面挡住**（用户报的就是这个）。
 *
 * ⇒ 给特效一个明确高于所有棋子精灵的 renderOrder，它一定最后画、一定在最上面。
 *   （**不是**抬高它的位置 —— 高度只影响观感，压不住排序。）
 *
 * 留了很大的空档（20 起步）：后面加"标记圈""霸体光环"之类的特效
 * 可以往 21、22 排，不用回来动棋子那几层。
 */
export const RENDER_ORDER_FX = 20;

/**
 * ============================================================
 *  ★ 卡面「存在感」（0.0.2 第 1 条 + 追加需求第 1、2 条）
 * ============================================================
 *
 * 【为什么是"只让背景变淡"？】
 * 第一版是把整张卡片贴图乘一个 `opacity`（CARD_OPACITY = 0.42）。
 * 但那样**信息一起被淡掉了** —— 星级包边、血条、名字全都变成半透明，
 * 在深色棋盘上根本看不清。你反馈的正是这一点。
 *
 * 现在的做法：
 *   · 卡片**背景**（主色渐变 + 立绘底衬）在**画布内**就画成半透明
 *     —— 它退成"底衬"，不抢小人的视线；
 *   · 星级 / 血条 / 名字 / 特质 全部单独成层或实色画，**不受这个值影响**；
 *   · 卡片精灵自己的 `opacity` 保持 1，一个像素都不再整体压淡。
 *
 * 【★ 0.0.2 追加：为什么要再降一半？】
 * 小人放大到接近一格之后，0.42 的底衬还是"一坨颜色"，
 * 把棋子挡得看不清地板和相邻格。降到 0.21（原来的一半）
 * 之后它只是"给小人的一圈底色"，不再抢视线。
 *
 * **注意：这个值只作用于"底面卡面"，不会动小人模型**
 * —— 小人是另一张精灵，它的透明度由 setChibiOpacity 单独控制。
 */
export const CARD_BODY_ALPHA = 0.21;

/**
 * 卡片精灵整体的不透明度。
 *
 * 【为什么是 1？】
 * 背景的透明已经**画进贴图里**了（见 CARD_BODY_ALPHA）。
 * 这里再乘一次的话会把信息层也一起淡掉 —— 那就退回老问题了。
 * 所以默认恒为 1，这个常量只作为"拖动结束后恢复原样"的目标值存在。
 */
export const CARD_OPACITY = 1;

/** 拖动时"被拖走的那只"的不透明度（整体压淡，要能看清底下的落点） */
export const CARD_OPACITY_DRAGGED = 0.45;

/**
 * 血条本身的高度（像素）。抽出来是因为 HP_BAR_AREA.y 要用它反推"贴着卡面下沿"。
 */
export const HP_BAR_H = 22;
/** 血条画布上下各留的发光余量（像素）：画布高 = HP_BAR_H + 2 * HP_BAR_PAD */
export const HP_BAR_PAD = 7;

/**
 * ============================================================
 *  ★ 藏品小圆点（0.0.3）
 * ============================================================
 *
 * 【这是什么？】
 * 需求原文：「在血条左侧加两个显示小圆圈，有装备显示为绿色，未装备显示为灰色」。
 * 所以这是**两个恒定的圆点**，表示"这个干员的 2 个 A 类藏品槽"：
 *   装满 = 两个绿点；装 1 个 = 一绿一灰；空着 = 两个灰点。
 *
 * 【为什么要挤血条的宽度？】
 * 圆点画在血条的**左边**，而卡片一共才 192px 宽，左边原本只留了 12px 边距
 * —— 塞不下两个 13px 的圆。所以把血条整体**右移**，
 * 空出左边这一条给圆点（见 HP_BAR_AREA.x 的算法）。
 * 血条因此短了 32px（168 → 136），长度信息仍然一眼可读。
 *
 * 【为什么圆点数写死 2，而不是读 ITEM_PER_UNIT？】
 * 因为 card-layout.ts 是**不依赖任何模块的叶子文件**（见文件顶部的说明），
 * 从 shared 里 import 常量会把这个约束打破。
 * 两边的一致性由单元测试钉住（见 unit-card-looks.test.ts 的藏品圆点分组）。
 */
export const ITEM_DOT_COUNT = 2;

/** 单个圆点的直径（像素） */
export const ITEM_DOT_SIZE = 13;

/** 两个圆点之间的缝（像素） */
export const ITEM_DOT_GAP = 3;

/** 两个圆点连起来的总宽 */
export const ITEM_DOTS_W = ITEM_DOT_COUNT * ITEM_DOT_SIZE + (ITEM_DOT_COUNT - 1) * ITEM_DOT_GAP;

/** 圆点区右边缘和血条左边缘之间的缝 */
export const ITEM_DOTS_GAP_TO_BAR = 3;

/**
 * 藏品圆点的像素布局（卡片坐标系，左上角为原点、y 向下）。
 *
 * 【为什么 y/h 和血条一模一样？】
 * 圆点要和血条**在同一条水平线上**才算"血条左侧"。
 * 共用 y/h 之后，"竖直中点落在卡片高度百分之几"这个换算（f）和血条完全相同，
 * 两边的摆放公式一模一样 —— 只要有一边改错了，测试就会把两个中心对不上号。
 */
export const ITEM_DOTS_AREA = {
  x: 12,
  y: CARD_H - HP_BAR_H - HP_BAR_PAD,
  w: ITEM_DOTS_W,
  h: HP_BAR_H,
};

/**
 * 血条的像素布局（卡片坐标系，左上角为原点、y 向下）。
 *
 * 【为什么要抽成常量？】
 * 血条现在是**独立的一张小精灵**，要浮在小人模型之上（0.0.2 追加需求第 1 条），
 * 所以"条画在画布哪个位置"和"这张小精灵摆在卡片哪里"必须是同一组数字，
 * 写两份迟早会对不上。这里就是那唯一一份。
 *
 * 【放在哪？】
 * **卡面最下沿**：血条矩形的下边 = 卡面下沿减去上下留白（`pad`），
 * 于是血条画布的底边正好贴住卡片精灵的底边（画布 = 血条 + 上下各 pad 的发光余量）。
 * 小人被抬到血条上方（见 CHIBI_FOOT_SCREEN），两者不重叠。
 *
 * 【★ 0.0.3：左边要让出 ITEM_DOTS_AREA】
 * x 不再是写死的 12，而是"圆点区右边缘 + 一条缝"；
 * w 也不再是 CARD_W - 24，而是"右边缘（CARD_W - 12）减掉新的 x"
 * —— 右边缘保持不动，血条只是从左边缩短，于是它和卡片右沿的间距和以前一样。
 *
 * 【★ 摆放方式有个坑，别改成 position】
 * 血条精灵是卡片的**子节点**，而子节点的 `position` 是**世界坐标系**里的偏移。
 * 相机的俯角会把"世界竖直方向"的位移在屏幕上压扁（实测只剩 ~42%），
 * 还会因为透视把血条整体往一边推（实测偏右 20px 上下）——
 * 拿 position.y 当"卡片高度的百分之几"用，出来的一定不是你想要的位置。
 * 所以血条的摆放走的是 `sprite.center`（**视图空间**里的偏移，不受俯角影响），
 * 具体换算见 sprite-graphics.ts 的 hpBarLocalTransform。
 */
export const HP_BAR_AREA = {
  /** 血条本身的矩形 */
  x: ITEM_DOTS_AREA.x + ITEM_DOTS_AREA.w + ITEM_DOTS_GAP_TO_BAR,
  /**
   * ★ 下边贴着卡面下沿：y + h + pad = CARD_H。
   * （+ pad 是因为画布比条子本身高一圈，那圈是描边和发光的余量。）
   */
  y: CARD_H - HP_BAR_H - HP_BAR_PAD,
  /** 右边缘仍然是 CARD_W - 12，只是左边缘右移了 → 条子变短 */
  w: CARD_W - 12 - (ITEM_DOTS_AREA.x + ITEM_DOTS_AREA.w + ITEM_DOTS_GAP_TO_BAR),
  h: HP_BAR_H,
  /** 上下额外留白：血条的描边和发光需要一点余量，否则会被画布裁掉 */
  pad: HP_BAR_PAD,
};

/**
 * ============================================================
 *  ★ 0.1.4：技能条（血条正下方那条细的）
 * ============================================================
 *
 * 【它显示什么？】
 *   · 平时：**蓝色** = 技能攒到多少了（法力 / 满蓝），"实时进度"；
 *   · 技能开启中（按时间的那类）：**红色**，随剩余时间越来越少；
 *   · 技能开启中（"接下来 N 次攻击"那类）：**橙色**，每攻击一次少一截；
 *   · 底槽一律**灰色**（需求指定），比血条细、但和血条一样长。
 *
 * 【为什么放在血条**下面**、而不是画进血条那张图？】
 *   1. 需求就是"血条下方"；
 *   2. 血条贴图的缓存键是「血量档位 + 敌我」，技能条是「技能状态 + 进度档」——
 *      两种变化毫无关系，画进同一张图的话"血量掉一格"会顺手重画技能条，
 *      缓存会从 42 张涨成 42×N 张。
 * 所以它和血条、星级、藏品圆点一样是**独立的第四张小精灵**，全场共享贴图。
 *
 * 【为什么 y 会算到卡面外面去？】
 * 血条的下边已经贴着卡面下沿了（见 HP_BAR_AREA），技能条只能往下排，
 * 于是它会**挂在卡片底边外面**一点点。这是刻意的：
 * 它是一张独立精灵、不会被卡片裁剪，看起来就是"卡片底下叠了两条状态条"。
 */
export const SKILL_BAR_H = 9;
/** 技能条画布的上下留白（比血条小一号：它本来就细，留太多会显得浮在空里） */

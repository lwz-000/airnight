/**
 * ============================================================
 *  ★ 0.3.4「新手教程」—— 内容与翻页状态
 * ============================================================
 *
 * 用户口径：
 *   · 第一次打开游戏**自动弹一次**；
 *   · 里面讲藏品、经济这些系统；
 *   · 能**翻页**；
 *   · 之后入口放在主界面角落，一颗很小的按钮。
 *
 * 【为什么内容是数据、不是一坨 innerHTML】
 *   ① 能单测（页数、每页都有内容、第一次才自动弹）；
 *   ② 以后加一页只是往数组里加一条，不用碰界面代码。
 *
 * 【★ 文案口径】
 *   所有数字都写**真值**（刷新 2 金、买经验 4 金、三张同名升星…），
 *   但**不写死"等级 1 级人口 1"这种会随后续改版漂移的细节** ——
 *   教程写错了比没有更糟（玩家会照着错的玩）。
 *   凡是"会变的"，一律写成规则本身（"人口上限 = 等级 + 藏品加成"），
 *   让玩家自己去界面上看当前值。
 */


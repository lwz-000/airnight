/** 一共几页 */
export function tutorialPageCount(): number {
  return TUTORIAL_PAGES.length;
}

/** 翻页：夹在 [0, 最后一页] 之间（越界就停在边界，不报错） */
export function clampTutorialPage(index: number): number {
  if (!Number.isFinite(index)) return 0;
  return Math.max(0, Math.min(TUTORIAL_PAGES.length - 1, Math.round(index)));
}

/** 第一次打开才自动弹 —— 看过（有标记）就不再弹 */
export function shouldAutoOpenTutorial(): boolean {
  try {
    const storage = globalThis.localStorage;
    // ★ 没有存储就等于"记不住"：每次进来都弹会变成骚扰，所以宁可不弹（入口还在角落）
    if (!storage) return false;
    return storage.getItem(TUTORIAL_SEEN_KEY) !== '1';
  } catch {
    return false;
  }
}

/** 记下"看过了"（关掉时调用；翻到最后一页点「开始游戏」也算） */
export function markTutorialSeen(): void {
  try {
    globalThis.localStorage?.setItem(TUTORIAL_SEEN_KEY, '1');
  } catch {
    // 存不进去就算了：下次再弹一次，不是什么大事
  }
}
